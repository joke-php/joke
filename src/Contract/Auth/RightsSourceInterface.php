<?php

declare(strict_types=1);

namespace Vasoft\Joke\Contract\Auth;

/**
 * Интерфейс источника прав доступа.
 *
 * Источник прав отвечает за получение списка разрешений для конкретного пользователя.
 * Права возвращаются в плоском виде (строки формата "module:right"),
 * что упрощает проверку через UserInterface::can().
 *
 * Источники могут использовать различные стратегии:
 * - Прямое хранение прав пользователя
 * - Ролевая модель (RBAC): роль → список прав
 * - Динамические правила (на основе времени, контекста и т.д.)
 *
 * AuthService агрегирует права от всех зарегистрированных источников.
 *
 * @see UserInterface::can()
 * @see AuthService
 *
 * @todo Заменить класс сервиса на реальный
 */
interface RightsSourceInterface
{
    /**
     * Получает список прав для указанного пользователя.
     *
     * Метод вызывается только для авторизованных пользователей.
     * Для AnonymousUser этот метод не должен вызываться.
     *
     * Каждый источник возвращает только те права, за которые он отвечает.
     * AuthService объединяет результаты от всех источников.
     *
     * @param UserInterface $user Авторизованный пользователь
     *
     * @return array<string> Плоский список прав в формате ["module:right", ...]
     *                       Например: ["users:view", "posts:edit", "admin:delete"]
     */
    public function getRights(UserInterface $user): array;
}
