<?php

declare(strict_types=1);

namespace Vasoft\Joke\Contract\Auth;

/**
 * Интерфейс аутентификатора.
 *
 * Аутентификатор отвечает за определение личности пользователя
 * на основе доступных данных (сессия, токен, cookie и т.д.).
 *
 * Каждый аутентификатор представляет собой отдельный способ
 * аутентификации (например, сессионный, JWT, API-ключ).
 *
 * AuthService последовательно опрашивает все зарегистрированные
 * аутентификаторы до первого успешного результата.
 *
 * @see AuthService
 *
 * @todo Изменить на реальный класс сервиса
 */
interface AuthenticatorInterface
{
    /**
     * Выполняет аутентификацию пользователя.
     *
     * Метод должен проверить наличие учетных данных в запросе/сессии
     * и попытаться идентифицировать пользователя.
     *
     * Если аутентификация не удалась или данные отсутствуют,
     * метод ДОЛЖЕН вернуть AnonymousUser, а НЕ выбрасывать исключение.
     *
     * @return UserInterface Объект пользователя (авторизованный или анонимный)
     */
    public function authenticate(): UserInterface;
}
