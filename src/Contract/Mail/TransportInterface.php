<?php

declare(strict_types=1);

namespace Vasoft\Joke\Contract\Mail;

use Vasoft\Joke\Mail\Email;
use Vasoft\Joke\Mail\MailException;

/**
 * Контракт для транспорта отправки электронной почты.
 *
 * Определяет единый метод для отправки писем, позволяя легко подменять
 * способы доставки (например, нативная mail(), SMTP или внешние API)
 * без изменения кода, использующего этот интерфейс.
 */
interface TransportInterface
{
    /**
     * Отправляет электронное письмо.
     *
     * Реализация этого метода должна взять объект Email, сформировать
     * необходимые заголовки и тело сообщения, а затем передать их
     * соответствующему сервису доставки.
     *
     * @param Email $email Объект письма, содержащий адресатов, тему и тело
     *
     * @throws MailException если произошла ошибка при формировании или отправке письма
     */
    public function send(Email $email): void;
}
